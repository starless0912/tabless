"""Sample content, so `tabless demo` shows you the thing instead of describing it.

The samples are written to a temporary directory, archived, and then the
temporary directory is deleted. That sequence is the point: what you end up
reading in the library is tabless's own copy, and the originals being gone
changes nothing. That is the difference between this and a list of bookmarks.

The batch is deliberately mixed -- two projects, four types, and all three kinds
of entry -- so the reader has something to actually group.
"""

