def install() -> list[dict]:
    """Write the samples, archive them, delete the originals, return the entries."""
    tmp = Path(tempfile.mkdtemp(prefix="tabless-demo-"))
    try:
        entries = []
        for sample in _SAMPLES:
            path = tmp / sample["name"]
            path.write_text(sample["html"], encoding="utf-8")
            entries.append(core.add_document(
                path, project=sample["project"], doctype=sample["type"],
                source="demo",
            ))

        board = tmp / "board"
        (board / "assets").mkdir(parents=True, exist_ok=True)
        (board / "assets" / "chart.svg").write_text(_CHART_SVG, encoding="utf-8")
        (board / "case-01.html").write_text(_SITE_CASE, encoding="utf-8")
        (board / "index.html").write_text(_SITE_INDEX, encoding="utf-8")
        entries.append(core.add_document(
            board / "index.html", project="acme", doctype="eval", source="demo",
        ))

        entries.append(core.add_live(
            target="http://localhost:5173/",
            project="orbital",
            title="Pass planner (live prototype)",
            hint="Run `npm run dev` in web/ first — tabless will not start it for you.",
            source="demo",
        ))
        return entries
    finally:
        # The originals go away and the library is unaffected. That is the demo.
        shutil.rmtree(tmp, ignore_errors=True)
